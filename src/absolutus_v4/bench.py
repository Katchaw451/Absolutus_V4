"""Planted-module recovery benchmark on a synthetic scale-free PPI.

Validation only: it measures how well each method recovers a known module and
how often it picks signal-free decoy hubs. It makes no statement about real biology.
"""
from __future__ import annotations

import argparse
import time
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

from .network import (adjacency, diamond, greedy_connected, prizes, recovery_metrics,
                      rwr, rwr_corrected, topk, transition)
from .sim import degrees, make_ppi, plant_module, simulate_z

METHODS = ["top_scores", "rwr", "rwr_corrected", "diamond", "greedy_connected"]
SETTINGS = [
    {"effect": 1.5, "degree_bias": 0.0},
    {"effect": 2.0, "degree_bias": 0.0},
    {"effect": 1.5, "degree_bias": 0.5},
    {"effect": 2.0, "degree_bias": 0.5},
]


def run_instance(seed, n_genes=2000, m=3, k=30, n_decoys=10, effect=2.0, degree_bias=0.0,
                 restart=0.5, n_perm=200, n_seeds_diamond=6):
    rng = np.random.default_rng(seed)
    g = make_ppi(n_genes, m, seed)
    module, decoys = plant_module(g, k, n_decoys, rng)
    deg = degrees(g)
    z = simulate_z(n_genes, module, effect, rng, deg, degree_bias)
    A = adjacency(g)
    W = transition(A)
    w = prizes(z)
    runs = {
        "top_scores": lambda: topk(np.abs(z), k),
        "rwr": lambda: topk(rwr(W, w, restart), k),
        "rwr_corrected": lambda: topk(rwr_corrected(W, w, deg, restart, n_perm, rng)[1], k),
        "diamond": lambda: diamond(A, topk(np.abs(z), n_seeds_diamond), k),
        "greedy_connected": lambda: greedy_connected(A, z, k),
    }
    rows = []
    for name, fn in runs.items():
        t = time.perf_counter()
        sel = fn()
        dt = time.perf_counter() - t
        rows.append({"seed": seed, "method": name, "seconds": dt,
                     **recovery_metrics(sel, module, decoys, deg)})
    return rows


def run_benchmark(n_seeds=20, **kw):
    out = []
    for si, s in enumerate(SETTINGS):
        for seed in range(n_seeds):
            for r in run_instance(seed, **s, **kw):
                out.append({"setting": si, **s, **r})
    return pd.DataFrame(out)


def summarise(df):
    g = df.groupby(["setting", "effect", "degree_bias", "method"])
    s = g[["precision", "decoy_rate", "mean_degree"]].agg(["mean", "sem"])
    s.columns = [f"{a}_{b}" for a, b in s.columns]
    s = s.reset_index()
    s["method"] = pd.Categorical(s["method"], METHODS, ordered=True)
    return s.sort_values(["setting", "method"]).reset_index(drop=True)


def paired_tests(df):
    rows = []
    for si, d in df.groupby("setting"):
        p = d.pivot(index="seed", columns="method", values="precision")
        for a, b in (("rwr_corrected", "rwr"), ("greedy_connected", "top_scores"),
                     ("greedy_connected", "rwr_corrected")):
            diff = (p[a] - p[b]).to_numpy()
            pv = float(wilcoxon(diff).pvalue) if np.any(diff != 0) else 1.0
            rows.append({"setting": si, "effect": d["effect"].iloc[0], "degree_bias": d["degree_bias"].iloc[0],
                         "comparison": f"{a} - {b}", "mean_diff_precision": float(diff.mean()),
                         "wilcoxon_p": pv, "n": len(diff)})
    return pd.DataFrame(rows)


def to_markdown(df: pd.DataFrame, floatfmt="{:.3f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v)
                                       for v in r) + " |")
    return "\n".join(lines)


def write_report(df, summ, tests, n_seeds, path):
    t = summ.copy()
    for c in ("precision", "decoy_rate", "mean_degree"):
        t[c] = t[f"{c}_mean"].map("{:.3f}".format) + " +/- " + (1.96 * t[f"{c}_sem"]).map("{:.3f}".format)
    t = t[["effect", "degree_bias", "method", "precision", "decoy_rate", "mean_degree"]]
    txt = f"""# Simulation benchmark (validation only)

Generated by `python -m absolutus_v4.bench --seeds {n_seeds}`. Synthetic scale-free PPI (n=2000, m=3),
planted connected module (k=30), 10 signal-free decoy hubs, {n_seeds} seeds per setting.
Cells are mean +/- 1.96*SEM (normal approximation). `effect` is the module z-shift,
`degree_bias` inflates noise on high-degree genes. These results validate the code and
characterise the methods on a toy generator; they say nothing about Alzheimer's or Parkinson's disease.

## Recovery

{to_markdown(t)}

## Paired comparisons (precision, Wilcoxon signed-rank across seeds)

{to_markdown(tests)}
"""
    Path(path).write_text(txt)


def plot(summ, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    settings = sorted(summ["setting"].unique())
    fig, axes = plt.subplots(2, len(settings), figsize=(4 * len(settings), 6.5), sharey="row")
    for j, si in enumerate(settings):
        d = summ[summ["setting"] == si]
        for i, (col, lab) in enumerate((("precision", "precision (module recovered)"),
                                        ("decoy_rate", "decoy hubs selected"))):
            ax = axes[i, j]
            ax.bar(range(len(d)), d[f"{col}_mean"], yerr=1.96 * d[f"{col}_sem"], capsize=3)
            ax.set_xticks(range(len(d)))
            ax.set_xticklabels(d["method"].astype(str), rotation=45, ha="right", fontsize=8)
            if i == 0:
                ax.set_title(f"effect={d['effect'].iloc[0]}, degree_bias={d['degree_bias'].iloc[0]}", fontsize=9)
            if j == 0:
                ax.set_ylabel(lab)
    fig.tight_layout()
    fig.savefig(path, dpi=130)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--out", default="results")
    ap.add_argument("--docs", default="docs/RESULTS_SIM.md")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    df = run_benchmark(a.seeds)
    summ, tests = summarise(df), paired_tests(df)
    df.to_csv(out / "sim_benchmark_raw.csv", index=False)
    summ.to_csv(out / "sim_benchmark_summary.csv", index=False)
    tests.to_csv(out / "sim_benchmark_paired_tests.csv", index=False)
    plot(summ, out / "sim_benchmark.png")
    write_report(df, summ, tests, a.seeds, a.docs)
    print(f"wrote {out}/ and {a.docs}")


if __name__ == "__main__":
    main()
