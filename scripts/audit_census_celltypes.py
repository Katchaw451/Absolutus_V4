"""Metadata-only audit 2: regions, cell types, assays and DOIs for the shortlisted datasets.
Writes docs/DATA_AUDIT_CELLTYPES.md. No expression data is read."""
import collections
from pathlib import Path

import cellxgene_census

CENSUS_VERSION = "2025-11-08"
GROUPS = {
    "AD SEA-AD DLPFC": ["6f7fd0f1-a2ed-4ff1-80d3-33dde731cbc3"],
    "AD Rexach cross-dementia": ["ac0c6561-7a48-4185-af6f-af799f699172"],
    "AD Layer-4 resilience": ["cff99df2-4904-44f7-9173-ff837f95606e"],
    "PD Multi-region atlas": ["d3cb449b-c2b1-4b50-a7f1-21203535fe61"],
    "PD Kamath (7 cell-type datasets)": [
        "2856d06c-0ff9-4e01-bfc9-202b74d0b60f", "251b1a7e-d050-4486-8d50-4c2619eb0f46",
        "07760522-707a-4a1c-8891-dbd1226d6b27", "f8d8b443-bca6-4c3c-9042-669dfb7f8030",
        "5829c7ba-697f-418e-8b98-d605b192dc48", "4dd1cd23-fc4d-4fd1-9709-602540f3ca6f",
        "f5be4b96-f5a3-4c3d-84ac-6f69daf744d5"],
}
COLS = ["donor_id", "tissue", "cell_type", "assay", "suspension_type"]
TOP = 25

L = ["# Census audit 2: regions and cell types (generated; metadata only)", "",
     f"Census version {CENSUS_VERSION}. Generated by `scripts/audit_census_celltypes.py`.", ""]
with cellxgene_census.open_soma(census_version=CENSUS_VERSION) as census:
    obs = census["census_data"]["homo_sapiens"].obs
    info = census["census_info"]["datasets"]
    for group, ids in GROUPS.items():
        cell = collections.defaultdict(lambda: [0, set()])
        tech = collections.Counter()
        for did in ids:
            for tbl in obs.read(value_filter=f"dataset_id == '{did}'", column_names=COLS):
                df = tbl.to_pandas().astype(str)
                for key, g in df.groupby(["tissue", "cell_type"]):
                    cell[key][0] += len(g)
                    cell[key][1].update(g["donor_id"].unique())
                for key, n in df.groupby(["assay", "suspension_type"]).size().items():
                    tech[key] += int(n)
        meta = info.read(value_filter="dataset_id in " + repr(ids),
                         column_names=["collection_name", "collection_doi"]).concat().to_pandas().drop_duplicates()
        tis = collections.defaultdict(lambda: [0, set()])
        for (t, c), (n, d) in cell.items():
            tis[t][0] += n
            tis[t][1] |= d
        L += [f"## {group}", "", "DOI: " + "; ".join(sorted(set(meta["collection_doi"].astype(str)))),
              "Assay / suspension: " + "; ".join(f"{a} / {s} ({n:,} cells)" for (a, s), n in tech.items()),
              f"Distinct cell types: {len({c for (_, c) in cell})}", "",
              "| tissue | cells | donors |", "|---|---|---|"]
        for t, (n, d) in sorted(tis.items(), key=lambda kv: -kv[1][0]):
            L.append(f"| {t} | {n:,} | {len(d)} |")
        L += ["", f"Top {TOP} (tissue, cell_type) by cells:", "",
              "| tissue | cell_type | cells | donors |", "|---|---|---|---|"]
        for (t, c), (n, d) in sorted(cell.items(), key=lambda kv: -kv[1][0])[:TOP]:
            L.append(f"| {t} | {c} | {n:,} | {len(d)} |")
        L.append("")
        print("done", group, flush=True)
Path("docs/DATA_AUDIT_CELLTYPES.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
