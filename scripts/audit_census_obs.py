"""Metadata-only audit of candidate CELLxGENE Census datasets (no expression data is read).
Writes docs/DATA_AUDIT_CENSUS.md and data/audit/census_obs_donors.csv (gitignored)."""
import collections
import itertools
from pathlib import Path

import cellxgene_census
import pandas as pd

CENSUS_VERSION = "2025-11-08"
DATASETS = {
    "AD SEA-AD MTG (whole taxonomy)": "c2876b1b-06d8-4d96-a56b-5304f815b99a",
    "AD SEA-AD DLPFC (whole taxonomy)": "6f7fd0f1-a2ed-4ff1-80d3-33dde731cbc3",
    "AD Rexach cross-dementia": "ac0c6561-7a48-4185-af6f-af799f699172",
    "AD Leng entorhinal cortex": "2727d83a-0af0-443a-bff8-58dc7028289a",
    "AD Leng superior frontal gyrus": "6c600df6-ddca-4628-a8bb-1d6de1e3f9b4",
    "AD Layer-4 resilience (all cells)": "cff99df2-4904-44f7-9173-ff837f95606e",
    "PD Multi-region PD atlas": "d3cb449b-c2b1-4b50-a7f1-21203535fe61",
    "PD Kamath DA neurons": "2856d06c-0ff9-4e01-bfc9-202b74d0b60f",
    "PD Kamath non-DA neurons": "251b1a7e-d050-4486-8d50-4c2619eb0f46",
    "PD Kamath astrocytes": "07760522-707a-4a1c-8891-dbd1226d6b27",
    "PD Kamath microglia": "f8d8b443-bca6-4c3c-9042-669dfb7f8030",
    "PD Kamath oligodendrocytes": "5829c7ba-697f-418e-8b98-d605b192dc48",
    "PD Kamath OPC": "4dd1cd23-fc4d-4fd1-9709-602540f3ca6f",
    "PD Kamath endothelial": "f5be4b96-f5a3-4c3d-84ac-6f69daf744d5",
}
COLS = ["donor_id", "disease", "tissue_general", "sex", "development_stage"]

rows = []
with cellxgene_census.open_soma(census_version=CENSUS_VERSION) as census:
    obs = census["census_data"]["homo_sapiens"].obs
    for name, did in DATASETS.items():
        acc = collections.Counter()
        for tbl in obs.read(value_filter=f"dataset_id == '{did}'", column_names=COLS):
            df = tbl.to_pandas().astype(str)
            for key, n in df.groupby(COLS).size().items():
                acc[key] += int(n)
        rows += [(name, *key, n) for key, n in acc.items()]
        print("read", name, sum(acc.values()), "cells", flush=True)

df = pd.DataFrame(rows, columns=["dataset"] + COLS + ["n_cells"])
join = lambda s: "; ".join(sorted(set(s)))
donor = df.groupby(["dataset", "donor_id"], as_index=False, sort=False).agg(
    disease=("disease", join), tissue=("tissue_general", join),
    sex=("sex", "first"), stage=("development_stage", "first"), n_cells=("n_cells", "sum"))
Path("data/audit").mkdir(parents=True, exist_ok=True)
donor.to_csv("data/audit/census_obs_donors.csv", index=False)

L = ["# Census metadata audit (generated; metadata only)", "",
     f"Census version {CENSUS_VERSION}. Generated by `scripts/audit_census_obs.py`. No expression data was read.",
     "Census has no PMI/batch; age comes from `development_stage`. `donor_id` naming is dataset-specific,",
     "so overlap between datasets is only meaningful when they share a naming scheme.", "",
     "| dataset | cells | donors | donors per disease label | tissues | median cells/donor |", "|---|---|---|---|---|---|"]
for name, d in donor.groupby("dataset", sort=False):
    dis = d.groupby("disease").size().to_dict()
    L.append(f"| {name} | {int(d.n_cells.sum()):,} | {len(d)} | {dis} | {sorted(set(d.tissue))} | {int(d.n_cells.median())} |")
L += ["", "## Shared donor_id strings between datasets", ""]
sets = {n: set(d.donor_id) for n, d in donor.groupby("dataset", sort=False)}
found = False
for a, b in itertools.combinations(sets, 2):
    k = len(sets[a] & sets[b])
    if k:
        found = True
        L.append(f"- {a} / {b}: {k} shared donor_id")
if not found:
    L.append("- none")
Path("docs/DATA_AUDIT_CENSUS.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
